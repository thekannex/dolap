import type { AssemblyType, BackType, DoorOverlayType } from './construction';
import type { RailType } from './hardware';

export type CabinetType = 'base' | 'wall' | 'tall' | 'drawer_base' | 'sink' | 'open_shelf' | 'filler';

/** Duvar üzerindeki sıra: alt dolaplar, üst dolaplar veya boy dolaplar. */
export type CabinetRow = 'base' | 'wall' | 'tall';

export interface CabinetState {
  code: string;
  name: string;
  type: CabinetType;
  width: number;
  height: number;
  depth: number;
  bodyThickness: number;
  assemblyType: AssemblyType;
  backType: BackType;
  backThickness: number;
  backChannelInset: number;
  backChannelDepth: number;
  doorGap: number;
  doorOverlayType: DoorOverlayType;
  halfOverlayAmount: number;
  doorCount: number;
  doorAutoGenerated: boolean;
  shelfCount: number;
  fixedShelfCount: number;
  shelfAutoGenerated: boolean;
  frontPullback: number;
  drawerCount: number;
  drawerRatios: number[];
  drawerAutoGenerated: boolean;
  railType: RailType;
  railWidthDeduction: number;
  hasBackPanel: boolean;
  backPanelCutout: boolean;
  isOpenShelf: boolean;
  railWidth: number;
  doorHingeSide: 'left' | 'right' | 'both';
}

/** Projeye kayıtlı dolap: hesap parametreleri + duvardaki yeri. */
export interface ProjectCabinet extends CabinetState {
  id: string;
  wallId: string | null;
  row: CabinetRow;
  /** Duvarın solundan uzaklık (mm). Boşsa dolap, sırasındaki bir önceki dolabın hemen yanına çizilir. */
  x: number | null;
  quantity: number;
  notes: string;
}
