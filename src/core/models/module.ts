import type { ConstructionParams, DoorOverlayType } from './construction';
import type { ValidationWarning } from './common';
import type { HardwareItem, RailType } from './hardware';
import type { Part } from './part';

export type ModuleType =
  | 'base' | 'wall' | 'tall' | 'drawer_base'
  | 'corner_blind' | 'corner_L' | 'corner_carousel'
  | 'sink' | 'appliance' | 'open_shelf'
  | 'wardrobe' | 'bookcase' | 'custom';

export type UsagePreset = 'plate' | 'jar' | 'pot' | 'custom';

export interface Compartment {
  id: string;
  type: 'shelf_fixed' | 'shelf_adjustable' | 'divider' | 'drawer_space';
  y: number;
  height: number;
  locked: boolean;
  usagePreset?: UsagePreset;
}

export interface DoorSpec {
  id: string;
  position: 'left' | 'right' | 'single';
  openDirection: 'left' | 'right' | 'up' | 'down';
  width: number;
  height: number;
  materialId: string;
  overlayType: DoorOverlayType;
  hingeCount: number;
  hingePositions: number[];
  locked: boolean;
}

export interface DoorLayout {
  count: number;
  doors: DoorSpec[];
  autoGenerated: boolean;
}

export interface DrawerSpec {
  id: string;
  frontHeight: number;
  frontWidth: number;
  boxWidth: number;
  boxDepth: number;
  boxHeight: number;
  railLength: number;
  y: number;
  locked: boolean;
}

export interface DrawerLayout {
  drawers: DrawerSpec[];
  ratios: number[];
  railType: RailType;
  autoGenerated: boolean;
}

export interface ModuleOptions {
  hasBackPanel: boolean;
  backPanelCutout: boolean; // Evye - arkalık kesik
  hasWaterTray: boolean; // Evye - su tepsisi
  isOpenShelf: boolean;
  customNotes: string;
}

export interface Module {
  id: string;
  code: string;
  name: string;
  type: ModuleType;
  outerWidth: number;
  outerHeight: number;
  outerDepth: number;
  construction: ConstructionParams;
  compartments: Compartment[];
  doorLayout: DoorLayout | null;
  drawerLayout: DrawerLayout | null;
  parts: Part[];
  hardware: HardwareItem[];
  warnings: ValidationWarning[];
  options: ModuleOptions;
}
