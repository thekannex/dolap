/** Dolap tipinin duvardaki varsayılan sırası. */
export function rowForType(type: CabinetType): CabinetRow {
  if (type === 'wall' || type === 'open_shelf') return 'wall';
  if (type === 'tall' || type === 'wardrobe' || type === 'bookcase') return 'tall';
  return 'base';
}

/**
 * Tip değişince tipe özgü ölçü ve seçenekleri uygular.
 * Gövde yapısı (kalınlık, arkalık, derz) korunur.
 */
export function applyTypePreset(cab: CabinetState, type: CabinetType, width: number = cab.width): CabinetState {
  const next: CabinetState = {
    ...cab,
    type,
    width,
    // Tipe özgü alanları sıfırla, sonra tipe göre doldur
    drawerCount: 0,
    drawerRatios: [],
    doorCount: 1,
    doorAutoGenerated: true,
    doorOpening: 'side',
    isOpenShelf: false,
    hasBackPanel: true,
    backPanelCutout: false,
    shelfCount: 1,
    fixedShelfCount: 0,
    plinthHeight: 0,
    hangerRodCount: 0,
    railWidth: 0,
    sink: null,
    interior: null,
    legHeight: 0,
  };

  switch (type) {
    case 'base':
      next.height = 720; next.depth = 560; next.railWidth = 100;
      break;
    case 'wall':
      next.height = 720; next.depth = 330; next.railWidth = 0;
      break;
    case 'tall':
      next.height = 2100; next.depth = 560; next.railWidth = 0;
      next.shelfCount = 4; next.fixedShelfCount = 1;
      break;
    case 'drawer_base':
      next.height = 720; next.depth = 560; next.railWidth = 100;
      next.drawerCount = 3; next.drawerRatios = [1, 1, 1];
      next.doorCount = 0; next.shelfCount = 0;
      break;
    case 'sink':
      next.height = 720; next.depth = 560; next.railWidth = 100;
      next.backPanelCutout = true; next.shelfCount = 0;
      next.sink = createSinkFromPreset(width >= 800 ? 'inset-86x50' : 'inset-50x50');
      break;
    case 'open_shelf':
      next.height = 720; next.depth = 330; next.railWidth = 0;
      next.isOpenShelf = true; next.doorCount = 0; next.hasBackPanel = false;
      next.shelfCount = 2;
      break;
    case 'filler':
      next.height = 720; next.depth = 560; next.railWidth = 0;
      next.doorCount = 0; next.shelfCount = 0; next.hasBackPanel = false;
      break;
    case 'wardrobe':
      next.height = 2100; next.depth = 580; next.plinthHeight = 80;
      next.hangerRodCount = 1; next.fixedShelfCount = 1; next.shelfCount = 0;
      break;
    case 'bookcase':
      next.height = 1800; next.depth = 300; next.plinthHeight = 60;
      next.isOpenShelf = true; next.doorCount = 0; next.shelfCount = 4;
      break;
    case 'shoe_cabinet':
      next.height = 1000; next.depth = 350; next.plinthHeight = 60; next.shelfCount = 3;
      break;
    case 'dresser':
      next.height = 800; next.depth = 450; next.plinthHeight = 60;
      next.drawerCount = 4; next.drawerRatios = [1, 1, 1, 1]; next.doorCount = 0; next.shelfCount = 0;
      break;
    case 'tv_unit':
      next.height = 450; next.depth = 400;
      next.doorAutoGenerated = false; next.doorCount = width >= 1200 ? 4 : 2;
      break;
    case 'custom':
      next.height = 1200; next.depth = 400; next.shelfCount = 2;
      break;
  }

  // İki kapaklı bağımsız mobilyada kapaklar ortadan açılır
  if (FURNITURE_TYPES.includes(type)) next.doorHingeSide = 'both';

  next.name = `${CABINET_TYPE_LABELS[type]} ${width}`;
  return next;
}

/** Projedeki mevcut kodlara göre sıradaki dolap kodunu üretir (M01, M02, ...). */
export function nextCabinetCode(existingCodes: string[]): string {
  let max = 0;
  for (const code of existingCodes) {
    const m = /^M(\d+)$/.exec(code);
    if (m) max = Math.max(max, Number(m[1]));
  }
  return `M${String(max + 1).padStart(2, '0')}`;
}

export function createProjectCabinet(params: {
  id: string;
  type: CabinetType;
  width: number;
  code: string;
  wallId?: string | null;
  x?: number | null;
  height?: number;
  base?: CabinetState;
}): ProjectCabinet {
  const preset = applyTypePreset(params.base ?? DEFAULT_CABINET, params.type, params.width);
  if (params.height) preset.height = params.height;
  return {
    ...preset,
    code: params.code,
    id: params.id,
    wallId: params.wallId ?? null,
    row: rowForType(params.type),
    x: params.x ?? null,
    quantity: 1,
    notes: '',
    groupId: null,
    elevation: null,
    shareLeft: false,
    shareBottom: false,
  };
}

/** Eski kayıtlardan gelen eksik alanları tamamlar. */
export function normalizeCabinet(raw: Partial<ProjectCabinet> & { id: string }): ProjectCabinet {
  const type = raw.type ?? 'base';
  return {
    ...DEFAULT_CABINET,
    wallId: null,
    row: rowForType(type),
    x: null,
    quantity: 1,
    notes: '',
    groupId: null,
    elevation: null,
    shareLeft: false,
    shareBottom: false,
    ...raw,
  } as ProjectCabinet;
}
