/** Kutunun içeriği: çizimde seçilir, dolabın kapak/çekmece/raf ayarlarına çevrilir. */
export type BoxContent = 'doors' | 'drawers' | 'open' | 'lift' | 'hanger' | 'niche';

export const BOX_CONTENTS: Array<{ value: BoxContent; label: string; hint: string }> = [
  { value: 'doors', label: 'Kapaklı', hint: 'Kapak ve hareketli raf' },
  { value: 'drawers', label: 'Çekmeceli', hint: 'Yüksekliğe göre çekmece sayısı' },
  { value: 'open', label: 'Açık raf', hint: 'Kapaksız, raflı (kitaplık)' },
  { value: 'lift', label: 'Yukarı açılır', hint: 'Kalkar / katlanır kapak' },
  { value: 'hanger', label: 'Askılı', hint: 'Kapaklı, askı borulu' },
  { value: 'niche', label: 'Boş niş', hint: 'Kapaksız, rafsız (TV, cihaz)' },
];

const TOL = 2;
// Kuşaklı (üst tablasız) dolap tipleri; bunların üstüne ortak tabla kurulamaz
const RAILED_TYPES = new Set(['base', 'drawer_base', 'sink']);

/** Ölçüleri koruyarak kutunun içeriğini ayarlar. */
export function applyBoxContent<T extends CabinetState>(cab: T, content: BoxContent): T {
  const next: T = {
    ...cab,
    isOpenShelf: false,
    doorCount: 1,
    doorAutoGenerated: true,
    doorOpening: 'side',
    drawerCount: 0,
    drawerRatios: [],
    hangerRodCount: 0,
    shelfCount: 0,
    fixedShelfCount: 0,
    hasBackPanel: true,
    railWidth: 0,
  };
  const shelvesFor = (h: number) => Math.max(0, Math.round(h / 350) - 1);
  // Geniş kutularda kapak 600mm'yi geçmesin diye kapak sayısı genişliğe göre
  const doorsFor = (w: number) => Math.max(1, Math.ceil(w / 600));
  switch (content) {
    case 'doors':
      next.doorAutoGenerated = false;
      next.doorCount = doorsFor(cab.width);
      next.shelfCount = shelvesFor(cab.height);
      break;
    case 'drawers': {
      const n = Math.min(6, Math.max(1, Math.round(cab.height / 180)));
      next.drawerCount = n;
      next.drawerRatios = Array(n).fill(1);
      next.doorCount = 0;
      break;
    }
    case 'open':
      next.isOpenShelf = true;
      next.doorCount = 0;
      next.shelfCount = shelvesFor(cab.height);
      break;
    case 'lift':
      next.doorOpening = 'up';
      next.shelfCount = cab.height > 500 ? 1 : 0;
      break;
    case 'hanger':
      next.doorAutoGenerated = false;
      next.doorCount = doorsFor(cab.width);
      next.hangerRodCount = 1;
      next.fixedShelfCount = cab.height > 1400 ? 1 : 0;
      break;
    case 'niche':
      next.isOpenShelf = true;
      next.doorCount = 0;
      break;
  }
  return next;
}

export function detectBoxContent(cab: CabinetState): BoxContent {
  if (cab.drawerCount > 0) return 'drawers';
  if (cab.isOpenShelf) return cab.shelfCount + cab.fixedShelfCount > 0 ? 'open' : 'niche';
  if (cab.doorOpening === 'up') return 'lift';
  if (cab.hangerRodCount > 0) return 'hanger';
  return 'doors';
}

export function boxContentLabel(content: BoxContent): string {
  return BOX_CONTENTS.find((c) => c.value === content)?.label ?? 'Kutu';
}

type Box = Pick<ProjectCabinet, 'id' | 'code' | 'width' | 'height' | 'depth' | 'x' | 'elevation' | 'groupId'> &
  Partial<Pick<ProjectCabinet, 'type' | 'railWidth' | 'bodyThickness'>>;

const bx = (c: Box) => c.x ?? 0;
const by = (c: Box) => c.elevation ?? 0;

export interface SharingCheck {
  /** Sol dikme ortak yapılabilir mi; yapılamıyorsa neden. */
  left: { possible: boolean; neighbor?: string; reason?: string };
  bottom: { possible: boolean; neighbor?: string; reason?: string };
}

/**
 * Ortak panelin mümkün olup olmadığını kontrol eder.
 * Sol: soldaki kutunun sağ dikmesi bu kutunun tüm yüksekliğini ve derinliğini kaplamalı.
 * Alt: alttaki kutunun üst tablası bu kutunun tüm genişliğini ve derinliğini kaplamalı.
 */
export function checkSharing(cab: Box, group: Box[]): SharingCheck {
  const others = group.filter((o) => o.id !== cab.id);
  const result: SharingCheck = { left: { possible: false }, bottom: { possible: false } };

  const leftN = others.find((o) => Math.abs(bx(o) + o.width - bx(cab)) <= TOL
    && by(o) < by(cab) + cab.height && by(o) + o.height > by(cab));
  if (!leftN) result.left.reason = 'Solunda bitişik kutu yok.';
  else if (by(leftN) > by(cab) + TOL || by(leftN) + leftN.height < by(cab) + cab.height - TOL) {
    result.left = { possible: false, neighbor: leftN.code, reason: `${leftN.code} bu kutunun tüm yüksekliğini kaplamıyor.` };
  } else if (leftN.depth < cab.depth - TOL) {
    result.left = { possible: false, neighbor: leftN.code, reason: `${leftN.code} daha sığ (${leftN.depth}mm).` };
  } else result.left = { possible: true, neighbor: leftN.code };

  const lowN = others.find((o) => Math.abs(by(o) + o.height - by(cab)) <= TOL
    && bx(o) < bx(cab) + cab.width && bx(o) + o.width > bx(cab));
  if (!lowN) result.bottom.reason = 'Altında bitişik kutu yok.';
  else if (bx(lowN) > bx(cab) + TOL || bx(lowN) + lowN.width < bx(cab) + cab.width - TOL) {
    result.bottom = { possible: false, neighbor: lowN.code, reason: `${lowN.code} bu kutunun tüm genişliğini kaplamıyor.` };
  } else if (lowN.depth < cab.depth - TOL) {
    result.bottom = { possible: false, neighbor: lowN.code, reason: `${lowN.code} daha sığ (${lowN.depth}mm).` };
  } else if (lowN.type && (lowN.railWidth ?? 0) > 0 && RAILED_TYPES.has(lowN.type)) {
    result.bottom = { possible: false, neighbor: lowN.code, reason: `${lowN.code} kuşaklı; üst tablası yok.` };
  } else result.bottom = { possible: true, neighbor: lowN.code };

  return result;
}

/** Hesap için kutunun ek seçenekleri: geçerli ortak paneller ve yerden yükseklik. */
export function compositionComputeOptions(cab: ProjectCabinet, all: ProjectCabinet[]): ComputeOptions {
  if (!cab.groupId) return {};
  const group = all.filter((c) => c.groupId === cab.groupId);
  const check = checkSharing(cab, group);
  return {
    omitLeftSide: cab.shareLeft && check.left.possible,
    omitBottom: cab.shareBottom && check.bottom.possible,
    raised: (cab.elevation ?? 0) > 0,
  };
}

export interface CompositionBounds { width: number; height: number; depth: number }

export function compositionBounds(group: Box[]): CompositionBounds {
  return {
    width: group.reduce((m, c) => Math.max(m, bx(c) + c.width), 0),
    height: group.reduce((m, c) => Math.max(m, by(c) + c.height), 0),
    depth: group.reduce((m, c) => Math.max(m, c.depth), 0),
  };
}

export function boxesOverlap(a: { x: number; y: number; w: number; h: number }, b: { x: number; y: number; w: number; h: number }): boolean {
  return a.x < b.x + b.w - TOL && b.x < a.x + a.w - TOL && a.y < b.y + b.h - TOL && b.y < a.y + a.h - TOL;
}

/** Çakışan kutular ve askıda (altı boş) kutular için uyarılar. */
export function validateComposition(group: Box[]): ValidationWarning[] {
  const warnings: ValidationWarning[] = [];
  const rect = (c: Box) => ({ x: bx(c), y: by(c), w: c.width, h: c.height });
  for (let i = 0; i < group.length; i++) {
    for (let j = i + 1; j < group.length; j++) {
      if (boxesOverlap(rect(group[i]), rect(group[j]))) {
        warnings.push({
          id: `overlap-${group[i].id}-${group[j].id}`, severity: 'error', ruleId: 'VAL_BOX_OVERLAP',
          message: `${group[i].code} ile ${group[j].code} üst üste biniyor.`,
          suggestion: 'Kutulardan birini taşıyın ya da küçültün.',
        });
      }
    }
  }
  for (const c of group) {
    if (by(c) <= TOL) continue;
    const supported = group.some((o) => o.id !== c.id && Math.abs(by(o) + o.height - by(c)) <= TOL
      && bx(o) < bx(c) + c.width && bx(o) + o.width > bx(c));
    if (!supported) {
      warnings.push({
        id: `hanging-${c.id}`, severity: 'info', ruleId: 'INFO_BOX_WALL_HUNG',
        message: `${c.code} yerden ${by(c)}mm yüksekte ve altında kutu yok; duvara asılacak.`,
        suggestion: 'Askı aparatı ya da duvar dübeli öngörün.',
      });
    }
  }
  return warnings;
}

