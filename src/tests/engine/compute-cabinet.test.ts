describe('computeCabinet — tabla birleşimi', () => {
  const box = (over: Partial<CabinetState> = {}) => base({ type: 'custom', width: 1000, height: 800, depth: 400, railWidth: 0, plinthHeight: 0, ...over });
  const p = (cab: CabinetState, id: string) => computeCabinet(cab).parts.find((x) => x.id === id)!;

  it('tablalar arada: dikme tam boy, tablalar W - 2t', () => {
    const c = box({ topJoint: 'between', bottomJoint: 'between' });
    expect(p(c, 'side-left').length).toBe(800);
    expect(p(c, 'top').length).toBe(964);
    expect(p(c, 'bottom').length).toBe(964);
  });

  it('üst tabla üstte, alt tabla arada', () => {
    const c = box({ topJoint: 'over', bottomJoint: 'between' });
    expect(p(c, 'side-left').length).toBe(782);
    expect(p(c, 'top').length).toBe(1000);
    expect(p(c, 'top').bands.left).toBeGreaterThan(0);
    expect(p(c, 'bottom').length).toBe(964);
    expect(p(c, 'bottom').bands.left).toBe(0);
  });

  it('iki tabla dışta: dikme H - 2t', () => {
    const c = box({ topJoint: 'over', bottomJoint: 'over' });
    expect(p(c, 'side-left').length).toBe(764);
    expect(p(c, 'bottom').length).toBe(1000);
    expect(p(c, 'bottom').bands.right).toBeGreaterThan(0);
  });

  it('bazalı dolapta alt tabla hep arada kalır', () => {
    const c = box({ bottomJoint: 'over', plinthHeight: 60 });
    expect(p(c, 'bottom').length).toBe(964);
  });

  it('alan yoksa eski montaj tipinden çıkarılır', () => {
    expect(jointsOf({ assemblyType: 'sides_in' })).toEqual({ topOver: true, bottomOver: true });
    expect(jointsOf({ assemblyType: 'sides_out', topJoint: 'over' })).toEqual({ topOver: true, bottomOver: false });
  });
});

describe('computeCabinet — kapak arkasındaki yan dikme', () => {
  const box = (over: Partial<CabinetState> = {}) => base({ type: 'custom', width: 600, height: 800, depth: 400, railWidth: 0, plinthHeight: 0, doorOverlayType: 'inset', ...over });
  const p = (cab: CabinetState, id: string) => computeCabinet(cab).parts.find((x) => x.id === id)!;

  it('gömme kapakta dikme geri çekilir, kapak dikme kadar büyür', () => {
    const plain = computeCabinet(box());
    const behind = computeCabinet(box({ leftSideBehind: true }));
    const side = behind.parts.find((x) => x.id === 'side-left')!;
    expect(side.name).toBe('Sol Yan Dikme (kapak arkasında)');
    expect(side.width).toBe(p(box(), 'side-left').width - 20);
    expect(side.bands.top).toBeGreaterThan(0);
    expect(p(box({ leftSideBehind: true }), 'side-right').width).toBe(p(box(), 'side-right').width);
    expect(behind.doorWidth).toBeCloseTo(plain.doorWidth + 18 / plain.doorCount, 0);
  });

  it('yarım bindirmede kapak dikmeyi tam örter, dikme geri çekilmez', () => {
    const half = { doorOverlayType: 'half' as const, halfOverlayAmount: 9 };
    const plain = computeCabinet(box(half));
    const behind = computeCabinet(box({ ...half, rightSideBehind: true }));
    expect(p(box({ ...half, rightSideBehind: true }), 'side-right').width).toBe(p(box(half), 'side-right').width);
    expect(behind.doorWidth).toBeCloseTo(plain.doorWidth + 9 / plain.doorCount, 0);
  });

  it('tam bindirmede işaretin etkisi yok', () => {
    const full = { doorOverlayType: 'full' as const };
    expect(computeCabinet(box({ ...full, leftSideBehind: true })).doorWidth).toBe(computeCabinet(box(full)).doorWidth);
    expect(p(box({ ...full, leftSideBehind: true }), 'side-left').name).toBe('Sol Yan Dikme');
  });

  it('tablalar dikmelerin arasındaysa köşe uyarısı verir', () => {
    const warn = (c: CabinetState) => computeCabinet(c).warnings.some((w) => w.ruleId === 'INFO_BEHIND_CORNER');
    expect(warn(box({ leftSideBehind: true, topJoint: 'between', bottomJoint: 'between' }))).toBe(true);
    expect(warn(box({ leftSideBehind: true, topJoint: 'over', bottomJoint: 'over' }))).toBe(false);
  });
});

