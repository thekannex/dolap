import { describe, it, expect } from 'vitest';
import { computeCabinet, partBandMeters, hasRails, isFloorStanding } from '../../core/engine/compute-cabinet';
import { applyTypePreset, DEFAULT_CABINET } from '../../core/engine/cabinet-factory';
import type { CabinetState } from '../../core/models/cabinet';

const base = (over: Partial<CabinetState> = {}): CabinetState => ({ ...DEFAULT_CABINET, ...over });
const part = (cab: CabinetState, id: string) => computeCabinet(cab).parts.find((p) => p.id === id);

describe('computeCabinet — gövde', () => {
  it('600×720×560 alt dolap: yanlar, taban, kuşaklar ve arkalık', () => {
    const r = computeCabinet(base());
    const ids = r.parts.map((p) => p.id);
    expect(ids).toEqual(expect.arrayContaining(['side-left', 'side-right', 'bottom', 'rail-front', 'rail-back', 'back', 'adj-shelf', 'door']));
    expect(ids).not.toContain('top');
    expect(part(base(), 'side-left')).toMatchObject({ length: 720, width: 560, thickness: 18 });
    expect(part(base(), 'bottom')).toMatchObject({ length: 564, width: 560 });
    expect(part(base(), 'rail-front')).toMatchObject({ length: 564, width: 100 });
    expect(r.innerWidth).toBe(564);
    expect(r.innerHeight).toBe(684);
  });

  it('kuşaksız dolapta üst tabla olur', () => {
    const wall = applyTypePreset(DEFAULT_CABINET, 'wall', 600);
    const ids = computeCabinet(wall).parts.map((p) => p.id);
    expect(ids).toContain('top');
    expect(ids).not.toContain('rail-front');
    expect(hasRails(wall)).toBe(false);
  });

  it('arkalıksız dolapta arkalık parçası yok', () => {
    expect(part(base({ hasBackPanel: false }), 'back')).toBeUndefined();
  });

  it('evye dolabı arkalık kesiği için bilgi verir', () => {
    const sink = applyTypePreset(DEFAULT_CABINET, 'sink', 800);
    const r = computeCabinet(sink);
    expect(r.parts.find((p) => p.id === 'back')?.name).toContain('kesik');
    expect(r.warnings.some((w) => w.ruleId === 'INFO_SINK_CUTOUT')).toBe(true);
  });

  it('geçersiz ölçüde parça üretmez, hata verir', () => {
    const r = computeCabinet(base({ width: 0 }));
    expect(r.parts).toHaveLength(0);
    expect(r.warnings[0].severity).toBe('error');
  });

  it('bant bilgisi: gövde ön kenarı tek boy, kapak dört kenar', () => {
    expect(part(base(), 'side-left')?.bands).toEqual({ top: 0.8, bottom: 0, left: 0, right: 0 });
    expect(part(base(), 'door')?.bands).toEqual({ top: 1, bottom: 1, left: 1, right: 1 });
    expect(part(base(), 'rail-back')?.bands).toEqual({ top: 0, bottom: 0, left: 0, right: 0 });
  });

  it('bant kalınlıkları seçenekle değiştirilebilir', () => {
    const r = computeCabinet(base(), { bodyBand: 0.4, frontBand: 2 });
    expect(r.parts.find((p) => p.id === 'bottom')?.bands.top).toBe(0.4);
    expect(r.parts.find((p) => p.id === 'door')?.bands.left).toBe(2);
  });
});

describe('computeCabinet — kapak', () => {
  it('600 genişlikte otomatik tek kapak, 800 de iki kapak', () => {
    expect(computeCabinet(base()).doorCount).toBe(1);
    const r = computeCabinet(base({ width: 800 }));
    expect(r.doorCount).toBe(2);
    expect(r.doorWidth).toBe(397);
    expect(r.doorHeight).toBe(717);
  });

  it('elle kapak sayısı', () => {
    const r = computeCabinet(base({ width: 900, doorAutoGenerated: false, doorCount: 3 }));
    expect(r.doorCount).toBe(3);
    expect(r.doorWidth).toBe(297);
  });

  it('elle sıfır kapak: kapak ve menteşe yok', () => {
    const r = computeCabinet(base({ doorAutoGenerated: false, doorCount: 0 }));
    expect(r.doorCount).toBe(0);
    expect(r.hardware.some((h) => h.key === 'hinge')).toBe(false);
  });

  it('gömme kapak iç ölçüden hesaplanır', () => {
    const r = computeCabinet(base({ doorOverlayType: 'inset' }));
    expect(r.doorWidth).toBe(558); // 564/1 - 2*3
    expect(r.doorHeight).toBe(678); // 684 - 2*3
  });

  it('yarım bindirme kapak', () => {
    const r = computeCabinet(base({ doorOverlayType: 'half', halfOverlayAmount: 9 }));
    expect(r.doorWidth).toBe(579); // (600 - 2*(18-9)) - 3
    expect(r.doorHeight).toBe(717);
  });

  it('menteşe sayısı kapak yüksekliğine göre', () => {
    const tall = applyTypePreset(DEFAULT_CABINET, 'tall', 600);
    const r = computeCabinet(tall);
    expect(r.hingeCount).toBe(5);
    expect(r.hardware.find((h) => h.key === 'hinge')?.quantity).toBe(5);
  });

  it('dar ve geniş kapak uyarıları', () => {
    const narrow = computeCabinet(base({ width: 300, doorAutoGenerated: false, doorCount: 2 }));
    expect(narrow.warnings.some((w) => w.ruleId === 'VAL_NARROW_DOOR')).toBe(true);
    const wide = computeCabinet(base({ width: 800, doorAutoGenerated: false, doorCount: 1 }));
    expect(wide.warnings.some((w) => w.ruleId === 'VAL_WIDE_DOOR')).toBe(true);
  });

  it('açık rafta kapak yok', () => {
    const open = applyTypePreset(DEFAULT_CABINET, 'open_shelf', 600);
    expect(computeCabinet(open).doorCount).toBe(0);
  });
});

describe('computeCabinet — çekmece', () => {
  const drawer = applyTypePreset(DEFAULT_CABINET, 'drawer_base', 600);

  it('üç eşit klapa ve kutu parçaları', () => {
    const r = computeCabinet(drawer);
    expect(r.drawerFrontHeights).toHaveLength(3);
    expect(r.drawerFrontWidth).toBe(597);
    expect(r.railLength).toBe(500);
    expect(r.drawerBoxWidth).toBe(538.5);
    const sides = r.parts.filter((p) => p.id.startsWith('drawer-side-'));
    expect(sides).toHaveLength(3);
    expect(sides[0]).toMatchObject({ length: 500, quantity: 2 });
    expect(r.parts.find((p) => p.id === 'drawer-bottom-0')).toMatchObject({ material: 'back', thickness: 8 });
    expect(r.hardware.find((h) => h.key === 'rail')).toMatchObject({ quantity: 3, unit: 'çift' });
    expect(r.hardware.find((h) => h.key === 'handle')?.quantity).toBe(3);
    expect(r.doorCount).toBe(0);
  });

  it('oranlara göre klapa yükseklikleri', () => {
    const r = computeCabinet({ ...drawer, drawerRatios: [1, 1, 2] });
    expect(r.drawerFrontHeights[2]).toBeGreaterThan(r.drawerFrontHeights[0] * 1.9);
  });

  it('oran sayısı uyuşmazsa eşit bölünür', () => {
    const r = computeCabinet({ ...drawer, drawerRatios: [1, 2] });
    expect(new Set(r.drawerFrontHeights).size).toBe(1);
  });

  it('metal kutuda yalnızca taban ve arka, set hırdavatı ve bilgi notu', () => {
    const r = computeCabinet({ ...drawer, railType: 'metal_box', railWidthDeduction: 0 });
    expect(r.parts.some((p) => p.id.startsWith('drawer-side-'))).toBe(false);
    expect(r.parts.some((p) => p.id === 'drawer-back-0')).toBe(true);
    expect(r.hardware.find((h) => h.key === 'metal_drawer')?.quantity).toBe(3);
    expect(r.warnings.some((w) => w.ruleId === 'INFO_METAL_BOX')).toBe(true);
  });

  it('gizli ray adı', () => {
    const r = computeCabinet({ ...drawer, railType: 'undermount', railWidthDeduction: 10 });
    expect(r.hardware.find((h) => h.key === 'rail')?.name).toContain('Gizli Ray');
  });

  it('sığ dolapta ray sığmazsa hata', () => {
    const r = computeCabinet({ ...drawer, depth: 200 });
    expect(r.railLength).toBe(0);
    expect(r.warnings.some((w) => w.ruleId === 'VAL_RAIL_DEPTH')).toBe(true);
  });
});

describe('computeCabinet — diğer', () => {
  it('dolgu paneli tek parça, hırdavatsız', () => {
    const filler = applyTypePreset(DEFAULT_CABINET, 'filler', 45);
    const r = computeCabinet(filler);
    expect(r.parts).toHaveLength(1);
    expect(r.parts[0]).toMatchObject({ length: 720, width: 45, material: 'front' });
    expect(r.hardware).toHaveLength(0);
  });

  it('sabit raf konfirmat sayısını artırır', () => {
    const a = computeCabinet(base()).hardware.find((h) => h.key === 'confirmat')!.quantity;
    const b = computeCabinet(base({ fixedShelfCount: 1 })).hardware.find((h) => h.key === 'confirmat')!.quantity;
    expect(b - a).toBe(6);
  });

  it('ayak: yere basan dolaplarda, geniş dolapta 6', () => {
    expect(computeCabinet(base()).hardware.find((h) => h.key === 'leg')?.quantity).toBe(4);
    expect(computeCabinet(base({ width: 1200 })).hardware.find((h) => h.key === 'leg')?.quantity).toBe(6);
    expect(isFloorStanding('wall')).toBe(false);
  });

  it('plakaya sığmayan parça için hata', () => {
    const r = computeCabinet(base({ height: 2900 }), { sheetWidth: 2800, sheetHeight: 2100 });
    expect(r.warnings.some((w) => w.ruleId === 'VAL_EXCEEDS_SHEET')).toBe(true);
  });

  it('partBandMeters kalınlığa göre metre toplar', () => {
    const m = partBandMeters({ length: 1000, width: 500, quantity: 2, bands: { top: 1, bottom: 1, left: 0.8, right: 0 } });
    expect(m.get(1)).toBe(4);
    expect(m.get(0.8)).toBe(1);
  });
});
